"""
Step 4 - Build the Excel analysis workbook (formula-driven, not pasted numbers).

Sheets
  About            - purpose, colour legend, how to use
  Data_Monthly     - Month x Region x Category facts (units, revenue, margin, target)
  Sales_Summary    - Year selector drives SUMIFS KPIs, region/category target achievement
  Seasonality      - AVERAGEIFS seasonality index by category + chart
  Inventory_Plan   - 2026 forecast with editable service level / lead time -> safety stock & order-up-to
  Dealer_Scorecard - dealer YoY growth, RANK, rating
"""
import sqlite3
from pathlib import Path

import pandas as pd
from openpyxl import Workbook
from openpyxl.chart import BarChart, LineChart, Reference
from openpyxl.formatting.rule import CellIsRule, ColorScaleRule
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter
from openpyxl.worksheet.datavalidation import DataValidation
from openpyxl.worksheet.table import Table, TableStyleInfo

ROOT = Path(__file__).resolve().parents[1]
DATA = ROOT / "data"
OUT = ROOT / "excel" / "Voltas_Sales_Demand_Analysis.xlsx"
OUT.parent.mkdir(exist_ok=True)

FONT = "Arial"
NAVY = "1F3A5F"
H_FILL = PatternFill("solid", fgColor=NAVY)
H_FONT = Font(name=FONT, bold=True, color="FFFFFF")
B_FONT = Font(name=FONT)
INPUT_FONT = Font(name=FONT, color="0000FF", bold=True)
INPUT_FILL = PatternFill("solid", fgColor="FFFF00")
TITLE = Font(name=FONT, bold=True, size=14, color=NAVY)
THIN = Border(bottom=Side(style="thin", color="D0D0D0"))
INR = '#,##0;(#,##0);"-"'
CR = '#,##0.00;(#,##0.00);"-"'
PCT = '0.0%;(0.0%);"-"'

REGIONS = ["North", "West", "South", "East"]
CATS = ["Split AC", "Window AC", "Air Cooler", "Refrigerator", "Washing Machine", "Water Dispenser"]
MONTHS = ["Jan", "Feb", "Mar", "Apr", "May", "Jun", "Jul", "Aug", "Sep", "Oct", "Nov", "Dec"]


def header(ws, row, col, labels):
    for j, lab in enumerate(labels):
        c = ws.cell(row=row, column=col + j, value=lab)
        c.fill, c.font = H_FILL, H_FONT
        c.alignment = Alignment(horizontal="center", vertical="center", wrap_text=True)


def style_body(ws, min_row, max_row, min_col, max_col):
    for r in ws.iter_rows(min_row=min_row, max_row=max_row, min_col=min_col, max_col=max_col):
        for c in r:
            if c.font != INPUT_FONT:
                c.font = B_FONT
            c.border = THIN


def chart_fix(ch):
    ch.roundedCorners = False
    if ch.legend is not None:
        ch.legend.overlay = False
    for t in (ch.title, ch.x_axis.title, ch.y_axis.title):
        if t is not None:
            t.overlay = False
    ch.x_axis.delete = False
    ch.y_axis.delete = False


def load():
    con = sqlite3.connect(DATA / "voltas_dw.db")
    monthly = pd.read_sql("""
        SELECT t.month, CAST(SUBSTR(t.month,1,4) AS INTEGER) AS year,
               CAST(SUBSTR(t.month,6,2) AS INTEGER) AS month_num,
               t.region, t.category, t.actual_units AS units,
               t.actual_revenue AS net_revenue,
               COALESCE(m.gm, 0) AS gross_margin, t.target_revenue
        FROM vw_target_achievement t
        LEFT JOIN (SELECT month, region, category, SUM(gross_margin) gm
                   FROM vw_sales_enriched GROUP BY month, region, category) m
          ON m.month = t.month AND m.region = t.region AND m.category = t.category
        ORDER BY t.month, t.region, t.category""", con)
    dealers = pd.read_sql("""
        SELECT dealer_name, distributor_name, region, dealer_tier, city_tier,
               SUM(CASE WHEN year = 2024 THEN net_revenue ELSE 0 END) AS rev_2024,
               SUM(CASE WHEN year = 2025 THEN net_revenue ELSE 0 END) AS rev_2025,
               SUM(CASE WHEN year = 2025 THEN units ELSE 0 END)       AS units_2025
        FROM vw_sales_enriched GROUP BY dealer_name, distributor_name, region, dealer_tier, city_tier
        ORDER BY rev_2025 DESC""", con)
    con.close()
    plan = pd.read_csv(DATA / "forecast_2026.csv")
    acc = pd.read_csv(DATA / "model_accuracy.csv")
    return monthly, dealers, plan, acc


def build():
    monthly, dealers, plan, acc = load()
    wb = Workbook()

    # ------------------------------------------------------------ About
    ws = wb.active
    ws.title = "About"
    ws["A1"] = "Voltas Sales, Channel & Demand Intelligence - Excel Analysis"
    ws["A1"].font = TITLE
    lines = [
        "Purpose: track sales vs target by region & category, understand seasonality, and plan 2026 stock levels.",
        "Data: synthetic, modelled on a seasonal consumer durables business (ACs, coolers, appliances), Jan-2023 to Dec-2025.",
        "Source: generated by python/01_generate_data.py, cleaned and modelled in SQL, exported by python/04_build_excel_report.py.",
        "",
        "Colour legend",
        "   Blue bold text on yellow = input you can change (year selector, service level, lead time).",
        "   Black text = formula. Every KPI recalculates when inputs or Data_Monthly change.",
        "",
        "How to use",
        "   Sales_Summary: pick a year in C3 - all KPIs and the region x category achievement grid update.",
        "   Inventory_Plan: change service level (C4) or lead time (C5) to see safety stock & order-up-to levels change.",
        "   Dealer_Scorecard: dealers ranked by 2025 revenue with YoY growth and an automatic rating.",
    ]
    for i, t in enumerate(lines, start=3):
        ws.cell(row=i, column=1, value=t).font = B_FONT
    ws["A7"].font = Font(name=FONT, bold=True)
    ws["A11"].font = Font(name=FONT, bold=True)
    ws["A8"].font, ws["A8"].fill = INPUT_FONT, INPUT_FILL
    ws.column_dimensions["A"].width = 120

    # ------------------------------------------------------------ Data_Monthly
    wd = wb.create_sheet("Data_Monthly")
    cols = ["Month", "Year", "Month_Num", "Region", "Category", "Units", "Net_Revenue", "Gross_Margin", "Target_Revenue"]
    header(wd, 1, 1, cols)
    for i, r in enumerate(monthly.itertuples(index=False), start=2):
        wd.cell(row=i, column=1, value=pd.Timestamp(r.month).to_pydatetime()).number_format = "mmm-yy"
        wd.cell(row=i, column=2, value=int(r.year))
        wd.cell(row=i, column=3, value=int(r.month_num))
        wd.cell(row=i, column=4, value=r.region)
        wd.cell(row=i, column=5, value=r.category)
        wd.cell(row=i, column=6, value=int(r.units)).number_format = INR
        wd.cell(row=i, column=7, value=float(r.net_revenue)).number_format = INR
        wd.cell(row=i, column=8, value=float(r.gross_margin)).number_format = INR
        wd.cell(row=i, column=9, value=float(r.target_revenue)).number_format = INR
    last = len(monthly) + 1
    tbl = Table(displayName="tblMonthly", ref=f"A1:I{last}")
    tbl.tableStyleInfo = TableStyleInfo(name="TableStyleMedium2", showRowStripes=True)
    wd.add_table(tbl)
    for c, w in zip("ABCDEFGHI", [10, 7, 10, 9, 17, 10, 15, 15, 15]):
        wd.column_dimensions[c].width = w
    wd.freeze_panes = "A2"
    for r in wd.iter_rows(min_row=2, max_row=last):
        for c in r:
            c.font = B_FONT
    rng = lambda col: f"Data_Monthly!${col}$2:${col}${last}"
    YR, REG, CAT, MN = rng("B"), rng("D"), rng("E"), rng("C")
    UNITS, REV, GM, TGT = rng("F"), rng("G"), rng("H"), rng("I")

    # ------------------------------------------------------------ Sales_Summary
    ss = wb.create_sheet("Sales_Summary")
    ss["B1"] = "Sales Performance Summary"
    ss["B1"].font = TITLE
    ss["B3"], ss["C3"] = "Select year", 2025
    ss["B3"].font = Font(name=FONT, bold=True)
    ss["C3"].font, ss["C3"].fill = INPUT_FONT, INPUT_FILL
    dv = DataValidation(type="list", formula1='"2023,2024,2025"', allow_blank=False)
    ss.add_data_validation(dv)
    dv.add("C3")

    header(ss, 5, 2, ["KPI", "Selected year", "Prior year", "YoY change"])
    kpis = [
        ("Net revenue (Rs Cr)", f"=SUMIFS({REV},{YR},$C$3)/10^7", f"=SUMIFS({REV},{YR},$C$3-1)/10^7", CR),
        ("Units sold", f"=SUMIFS({UNITS},{YR},$C$3)", f"=SUMIFS({UNITS},{YR},$C$3-1)", INR),
        ("Target (Rs Cr)", f"=SUMIFS({TGT},{YR},$C$3)/10^7", f"=SUMIFS({TGT},{YR},$C$3-1)/10^7", CR),
        ("Target achievement", "=IFERROR(C6/C8,0)", "=IFERROR(D6/D8,0)", PCT),
        ("Gross margin %", f"=IFERROR(SUMIFS({GM},{YR},$C$3)/SUMIFS({REV},{YR},$C$3),0)",
         f"=IFERROR(SUMIFS({GM},{YR},$C$3-1)/SUMIFS({REV},{YR},$C$3-1),0)", PCT),
        ("Avg realised price (Rs)", "=IFERROR(C6*10^7/C7,0)", "=IFERROR(D6*10^7/D7,0)", INR),
    ]
    for i, (lab, cur, prev, fmt) in enumerate(kpis, start=6):
        ss.cell(row=i, column=2, value=lab)
        ss.cell(row=i, column=3, value=cur).number_format = fmt
        ss.cell(row=i, column=4, value=prev).number_format = fmt
        ss.cell(row=i, column=5, value=f'=IF(D{i}=0,"n/a",C{i}/D{i}-1)').number_format = PCT
    style_body(ss, 6, 11, 2, 5)
    ss["B12"] = "Prior year shows '-' for 2023 (no 2022 data)."
    ss["B12"].font = Font(name=FONT, italic=True, color="808080")

    # Target achievement grid region x category
    ss["B14"] = "Target achievement % - Region x Category (selected year)"
    ss["B14"].font = Font(name=FONT, bold=True, size=12, color=NAVY)
    header(ss, 15, 2, ["Region"] + CATS + ["Total"])
    for i, reg in enumerate(REGIONS, start=16):
        ss.cell(row=i, column=2, value=reg)
        for j, cat in enumerate(CATS, start=3):
            ss.cell(row=i, column=j, value=(
                f'=IFERROR(SUMIFS({REV},{YR},$C$3,{REG},$B{i},{CAT},{get_column_letter(j)}$15)'
                f'/SUMIFS({TGT},{YR},$C$3,{REG},$B{i},{CAT},{get_column_letter(j)}$15),0)')).number_format = PCT
        ss.cell(row=i, column=9, value=(
            f'=IFERROR(SUMIFS({REV},{YR},$C$3,{REG},$B{i})/SUMIFS({TGT},{YR},$C$3,{REG},$B{i}),0)')).number_format = PCT
    style_body(ss, 16, 19, 2, 9)
    ss.conditional_formatting.add("C16:I19", ColorScaleRule(start_type="num", start_value=0.8, start_color="F8696B",
                                                            mid_type="num", mid_value=1.0, mid_color="FFEB84",
                                                            end_type="num", end_value=1.15, end_color="63BE7B"))

    # Revenue by region by year (for chart)
    ss["B22"] = "Net revenue by region (Rs Cr)"
    ss["B22"].font = Font(name=FONT, bold=True, size=12, color=NAVY)
    header(ss, 23, 2, ["Region", "2023", "2024", "2025", "CAGR 23-25"])
    for i, reg in enumerate(REGIONS, start=24):
        ss.cell(row=i, column=2, value=reg)
        for j, y in enumerate([2023, 2024, 2025], start=3):
            ss.cell(row=i, column=j, value=f"=SUMIFS({REV},{YR},{y},{REG},$B{i})/10^7").number_format = CR
        ss.cell(row=i, column=6, value=f"=IFERROR((E{i}/C{i})^(1/2)-1,0)").number_format = PCT
    style_body(ss, 24, 27, 2, 6)
    ch = BarChart()
    ch.type, ch.grouping = "col", "clustered"
    ch.title, ch.y_axis.title = "Net revenue by region", "Rs Cr"
    ch.add_data(Reference(ss, min_col=3, max_col=5, min_row=23, max_row=27), titles_from_data=True)
    ch.set_categories(Reference(ss, min_col=2, min_row=24, max_row=27))
    ch.height, ch.width = 7.5, 16
    chart_fix(ch)
    ss.add_chart(ch, "H22")
    ss.column_dimensions["B"].width = 24
    for c in "CDEFGHI":
        ss.column_dimensions[c].width = 15

    # ------------------------------------------------------------ Seasonality
    se = wb.create_sheet("Seasonality")
    se["B1"] = "Seasonality - average monthly units and seasonality index (all regions, 2023-2025)"
    se["B1"].font = TITLE
    header(se, 3, 2, ["Month_Num", "Month"] + CATS)
    for i in range(12):
        r = 4 + i
        se.cell(row=r, column=2, value=i + 1)
        se.cell(row=r, column=3, value=MONTHS[i])
        for j, cat in enumerate(CATS, start=4):
            col = get_column_letter(j)
            se.cell(row=r, column=j, value=f"=SUMIFS({UNITS},{CAT},{col}$3,{MN},$B{r})/3").number_format = INR
    se["B16"] = "Annual avg"
    for j in range(4, 10):
        col = get_column_letter(j)
        se.cell(row=16, column=j, value=f"=AVERAGE({col}4:{col}15)").number_format = INR
    style_body(se, 4, 16, 2, 9)
    se["B16"].font = Font(name=FONT, bold=True)
    se["B17"] = "Monthly units are averaged over 3 years (2023-2025), summed across regions."
    se["B17"].font = Font(name=FONT, italic=True, color="808080")

    se["B19"] = "Seasonality index (1.00 = average month; >1.3 = peak, <0.7 = trough)"
    se["B19"].font = Font(name=FONT, bold=True, size=12, color=NAVY)
    header(se, 20, 2, ["Month_Num", "Month"] + CATS)
    for i in range(12):
        r = 21 + i
        se.cell(row=r, column=2, value=i + 1)
        se.cell(row=r, column=3, value=MONTHS[i])
        for j in range(4, 10):
            col = get_column_letter(j)
            se.cell(row=r, column=j, value=f"=IFERROR({col}{4 + i}/{col}$16,0)").number_format = "0.00"
    style_body(se, 21, 32, 2, 9)
    se.conditional_formatting.add("D21:I32", ColorScaleRule(start_type="num", start_value=0.2, start_color="5A8AC6",
                                                            mid_type="num", mid_value=1, mid_color="FFFFFF",
                                                            end_type="num", end_value=2.5, end_color="F8696B"))
    lc = LineChart()
    lc.title, lc.y_axis.title = "Seasonality index by category", "Index"
    lc.add_data(Reference(se, min_col=4, max_col=9, min_row=20, max_row=32), titles_from_data=True)
    lc.set_categories(Reference(se, min_col=3, min_row=21, max_row=32))
    lc.height, lc.width = 9, 18
    chart_fix(lc)
    se.add_chart(lc, "K3")
    for c in "BCDEFGHI":
        se.column_dimensions[c].width = 14

    # ------------------------------------------------------------ Inventory_Plan
    ip = wb.create_sheet("Inventory_Plan")
    ip["B1"] = "2026 Demand Forecast & Stocking Plan (Region x Category x Month)"
    ip["B1"].font = TITLE
    ip["B3"] = "Planning assumptions"
    ip["B3"].font = Font(name=FONT, bold=True)
    ip["B4"], ip["C4"] = "Target service level", 0.95
    ip["B5"], ip["C5"] = "Lead time (months)", 1
    ip["B6"], ip["C6"] = "z-score (from service level)", "=NORMSINV(C4)"
    for c in ("C4", "C5"):
        ip[c].font, ip[c].fill = INPUT_FONT, INPUT_FILL
    ip["C4"].number_format, ip["C6"].number_format = "0%", "0.00"
    ip["D4"] = "Change service level / lead time -> safety stock and order-up-to levels recalculate."
    ip["D4"].font = Font(name=FONT, italic=True, color="808080")
    ip["D6"] = "Forecast error % = 2025 backtest WAPE of the production model for that region x category."
    ip["D6"].font = Font(name=FONT, italic=True, color="808080")

    err = acc[acc.model == "Ensemble"].set_index(["region", "category"])["wape"]
    hdr = ["Month", "Region", "Category", "Forecast units", "Lower 80%", "Upper 80%",
           "Forecast error %", "Safety stock", "Order-up-to level", "Share of category-year"]
    header(ip, 8, 2, hdr)
    plan = plan.sort_values(["region", "category", "month"]).reset_index(drop=True)
    first, lastp = 9, 8 + len(plan)
    for i, r in enumerate(plan.itertuples(index=False), start=first):
        ip.cell(row=i, column=2, value=pd.Timestamp(r.month).to_pydatetime()).number_format = "mmm-yy"
        ip.cell(row=i, column=3, value=r.region)
        ip.cell(row=i, column=4, value=r.category)
        ip.cell(row=i, column=5, value=int(r.forecast_units)).number_format = INR
        ip.cell(row=i, column=6, value=int(r.lower_80)).number_format = INR
        ip.cell(row=i, column=7, value=int(r.upper_80)).number_format = INR
        e = ip.cell(row=i, column=8, value=float(err.loc[(r.region, r.category)]))
        e.number_format, e.font = PCT, Font(name=FONT, color="0000FF")
        ip.cell(row=i, column=9, value=f"=ROUND($C$6*H{i}*E{i}*SQRT($C$5),0)").number_format = INR
        ip.cell(row=i, column=10, value=f"=E{i}+I{i}").number_format = INR
        ip.cell(row=i, column=11, value=f"=IFERROR(E{i}/SUMIFS($E${first}:$E${lastp},$C${first}:$C${lastp},C{i},$D${first}:$D${lastp},D{i}),0)").number_format = PCT
    style_body(ip, first, lastp, 2, 11)
    for i in range(first, lastp + 1):
        ip.cell(row=i, column=8).font = Font(name=FONT, color="0000FF")
    ip.conditional_formatting.add(f"K{first}:K{lastp}", CellIsRule(operator="greaterThanOrEqual", formula=["0.15"],
                                                                     fill=PatternFill("solid", fgColor="FCE4D6")))
    ip.freeze_panes = "B9"
    for c, w in zip("BCDEFGHIJK", [10, 9, 17, 14, 11, 11, 15, 13, 16, 18]):
        ip.column_dimensions[c].width = w
    ip.column_dimensions["B"].width = 26
    ip.cell(row=lastp + 2, column=2, value="Orange = month carries >=15% of that category's annual volume (peak - pre-build stock).").font = \
        Font(name=FONT, italic=True, color="808080")

    # ------------------------------------------------------------ Dealer_Scorecard
    dsc = wb.create_sheet("Dealer_Scorecard")
    dsc["B1"] = "Dealer Scorecard - 2025 vs 2024"
    dsc["B1"].font = TITLE
    h = ["Dealer", "Distributor", "Region", "Dealer tier", "City tier", "Revenue 2024 (Rs)", "Revenue 2025 (Rs)",
         "Units 2025", "YoY growth", "National rank", "Rank in region", "Share of 2025 revenue", "Rating"]
    header(dsc, 3, 2, h)
    f0, f1 = 4, 3 + len(dealers)
    for i, r in enumerate(dealers.itertuples(index=False), start=f0):
        dsc.cell(row=i, column=2, value=r.dealer_name)
        dsc.cell(row=i, column=3, value=r.distributor_name)
        dsc.cell(row=i, column=4, value=r.region)
        dsc.cell(row=i, column=5, value=r.dealer_tier)
        dsc.cell(row=i, column=6, value=r.city_tier)
        dsc.cell(row=i, column=7, value=float(r.rev_2024)).number_format = INR
        dsc.cell(row=i, column=8, value=float(r.rev_2025)).number_format = INR
        dsc.cell(row=i, column=9, value=int(r.units_2025)).number_format = INR
        dsc.cell(row=i, column=10, value=f"=IFERROR(H{i}/G{i}-1,0)").number_format = PCT
        dsc.cell(row=i, column=11, value=f"=RANK(H{i},$H${f0}:$H${f1},0)")
        dsc.cell(row=i, column=12, value=f"=COUNTIFS($D${f0}:$D${f1},D{i},$H${f0}:$H${f1},\">\"&H{i})+1")
        dsc.cell(row=i, column=13, value=f"=H{i}/SUM($H${f0}:$H${f1})").number_format = "0.00%"
        dsc.cell(row=i, column=14, value=f'=IF(AND(J{i}>=0.05,L{i}<=5),"Star",IF(J{i}>=0,"Stable",IF(J{i}>=-0.1,"Watch","At risk")))')
    style_body(dsc, f0, f1, 2, 14)
    dsc.conditional_formatting.add(f"J{f0}:J{f1}", ColorScaleRule(start_type="num", start_value=-0.25, start_color="F8696B",
                                                                  mid_type="num", mid_value=0, mid_color="FFFFFF",
                                                                  end_type="num", end_value=0.25, end_color="63BE7B"))
    for txt, col in (("At risk", "F8CBAD"), ("Star", "C6EFCE")):
        dsc.conditional_formatting.add(f"N{f0}:N{f1}", CellIsRule(operator="equal", formula=[f'"{txt}"'],
                                                                  fill=PatternFill("solid", fgColor=col)))
    dsc.cell(row=f1 + 2, column=2, value=("Rating rule: Star = growth >=5% and top-5 in region; Stable = growth >=0%; "
                                          "Watch = decline up to 10%; At risk = decline >10%.")).font = Font(name=FONT, italic=True, color="808080")
    dsc.freeze_panes = "C4"
    dsc.auto_filter.ref = f"B3:N{f1}"
    for c, w in zip("BCDEFGHIJKLMN", [12, 28, 9, 11, 9, 16, 16, 10, 11, 11, 12, 13, 10]):
        dsc.column_dimensions[c].width = w

    for s in wb.worksheets:
        s.sheet_view.showGridLines = False
    wb.save(OUT)
    print(f"Saved {OUT}")


if __name__ == "__main__":
    build()
